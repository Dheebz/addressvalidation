using System.Globalization;
using System.Net;
using Address.Data;

namespace Gnaf.Admin;

/// <summary>Renders operator-facing status and release controls from trusted service snapshots.</summary>
public static class AdminPage
{
    /// <summary>Turns a source version such as 2026_08 into a readable release name.</summary>
    public static string ReleaseName(string version)
    {
        var parts = version.Split('_');
        return parts.Length == 2 && int.TryParse(parts[0], out var year) &&
            int.TryParse(parts[1], out var month) && month is >= 1 and <= 12
            ? CultureInfo.InvariantCulture.DateTimeFormat.GetMonthName(month) + " " + year
            : version;
    }

    /// <summary>Renders a self-contained operator dashboard from current service snapshots.</summary>
    public static string Render(IReadOnlyList<DatasetDetail> versions, MaintenanceJob? job,
        bool apiReady, IReadOnlyList<ApiReplicaStatus> apiReplicas, long? databaseBytes, ClusterStatus cluster, bool dataAvailable,
        string notice, string error, string? csrfToken = null, IReadOnlyList<AdminEvent>? events = null,
        string operatorName = "Local development", int? retentionHours = BulkRetention.DefaultHours,
        HousekeepingSnapshot? housekeeping = null)
    {
        // Dataset metadata, notices, actor names, and request IDs can all
        // contain external text. Encode before interpolating into HTML.
        static string E(string? value) => WebUtility.HtmlEncode(value ?? "");
        static string Count(long? value) => value?.ToString("N0", CultureInfo.InvariantCulture) ?? "—";
        static string Size(long? value) => value is null ? "—" :
            (value.Value / 1024d / 1024 / 1024).ToString("0.00", CultureInfo.InvariantCulture) + " GiB";
        static string Time(DateTime? value) => value is null ? "—" :
            value.Value.ToUniversalTime().ToString("d MMM yyyy, HH:mm 'UTC'", CultureInfo.InvariantCulture);
        static string Status(string value) => value switch
        {
            "ACTIVE" => "Live",
            "READY" => "Ready for review",
            "RETIRED" => "Previous",
            "FAILED" => "Needs attention",
            "DOWNLOADING" => "Downloading",
            "CHECKING_SCHEMA" => "Checking archive format",
            "LOADING" => "Importing",
            "TRANSFORMING" => "Building address search",
            "BUILDING_INDEXES" => "Building indexes",
            "VALIDATING" => "Checking quality",
            _ => "Preparing"
        };

        // Only complete national releases may appear in activation and
        // rollback controls; sample and regional records stay informational.
        var national = versions.Where(v => v.DatasetName == "G-NAF" && v.Scope == "ALL")
            .OrderByDescending(v => v.SourceVersion, StringComparer.Ordinal).ToArray();
        var active = national.FirstOrDefault(v => v.Status == "ACTIVE");
        var candidate = national.FirstOrDefault(v => v.Status == "READY");
        var prior = national.Where(v => v.Status == "RETIRED")
            .OrderByDescending(v => v.RetiredAt).FirstOrDefault();
        var other = versions.Where(v => v.DatasetName != "G-NAF" || v.Scope != "ALL").ToArray();
        var activeName = !dataAvailable ? "Release status temporarily unavailable" :
            active is null ? "No national release live" : ReleaseName(active.SourceVersion);
        var activeVersion = active?.SourceVersion ?? "—";
        var apiClass = apiReady ? "good" : "bad";
        var apiText = apiReady ? "API responding" : "API needs attention";
        var noticeBox = notice.Length > 0 ? $"<div class='flash success' role='status'>{E(notice)}</div>" : "";
        var errorBox = error.Length > 0 ? $"<div class='flash error' role='alert'>{E(error)}</div>" : "";
        // The request token is HTML encoded even though it is generated by ASP.NET Core.
        var csrfField = $"<input type='hidden' name='__RequestVerificationToken' value='{E(csrfToken)}'>";
        var activity = events is null || events.Count == 0
            ? "<p class='muted'>No operator actions recorded yet.</p>"
            : "<ul class='activity-list'>" + string.Join("", events.Select(item =>
                $"<li><span class='badge {EventClass(item.Outcome)}'>{E(item.Outcome)}</span> " +
                $"<strong>{E(item.Action)}</strong> {E(item.SourceVersion)}" +
                $"<small>{E(item.Detail)} · {Time(item.OccurredAt)} · {E(item.Actor)} · {E(item.RequestId)}</small></li>")) + "</ul>";

        var comparison = !dataAvailable ? "<p class='muted'>Release details will return when the database is available.</p>" :
            candidate is null ? "<p class='muted'>No prepared national release is waiting for review.</p>" :
            $"""
            <div class="release-compare">
              <div><span class="eyebrow">Live now</span><strong>{E(activeName)}</strong><span>{Count(active?.AddressCount)} addresses</span></div>
              <div class="compare-arrow" aria-hidden="true">→</div>
              <div><span class="eyebrow">Ready to activate</span><strong>{E(ReleaseName(candidate.SourceVersion))}</strong><span>{Count(candidate.AddressCount)} addresses</span></div>
            </div>
            <div class="checks">
              <span class="check">✓ Import completed</span>
              <span class="check">✓ Quality checks passed</span>
              <span class="check">✓ {candidate.GeocodeCoverage:P2} geocoded</span>
            </div>
            {(active is not null && string.CompareOrdinal(candidate.SourceVersion, active.SourceVersion) < 0
                ? "<p class='muted'>Historical replay: a lower count than the newer live release is expected. Raw source counts, national coverage and geocoding were still checked.</p>"
                : "")}
            <p class="muted">Address count change: {Count(candidate.AddressCount - active?.AddressCount)}. Activating changes the database view; the API process keeps running.</p>
            <form method="post" action="/promote/{E(candidate.SourceVersion)}" data-confirm="Activate {E(ReleaseName(candidate.SourceVersion))}? The API will begin using this release immediately.">
              {csrfField}
              <button class="button primary" type="submit">Activate {E(ReleaseName(candidate.SourceVersion))}</button>
            </form>
            """;

        var rollback = !dataAvailable ? "<p class='muted'>Rollback controls will return when the database is available.</p>" :
            prior is null ? "<p class='muted'>A previous national release is not available yet.</p>" :
            $"""
            <p>Restore <strong>{E(ReleaseName(prior.SourceVersion))}</strong> if the current data causes a problem. Its {Count(prior.AddressCount)} addresses are retained locally.</p>
            <form method="post" action="/rollback" data-confirm="Restore {E(ReleaseName(prior.SourceVersion))}? This immediately changes the release used by the API.">
              {csrfField}
              <button class="button secondary" type="submit">Restore {E(ReleaseName(prior.SourceVersion))}</button>
            </form>
            """;

        var deleteRetired = !dataAvailable ? "<p class='muted'>Retained release details will return when the database is available.</p>" :
            prior is null ? "<p class='muted'>No previous national release is stored. The live release remains available.</p>" :
            job?.Status is "QUEUED" or "RUNNING"
                ? "<p class='muted'>Wait for the current release preparation to finish before deleting retained data.</p>"
                : $"""
                  <p><strong>{E(ReleaseName(prior.SourceVersion))}</strong> is the previous release. Its serving data and indexes use about <strong>{Size(prior.TableBytes)} per database copy</strong>.</p>
                  <p>Deleting it frees that space after PostgreSQL finishes cleanup. <strong>{E(activeName)} stays live</strong>, but rollback to {E(ReleaseName(prior.SourceVersion))} will no longer be available. You can download and import that official release again later.</p>
                  <form class="delete-release-form" method="post" action="/releases/{E(prior.SourceVersion)}/delete">
                    {csrfField}
                    <label for="confirm-delete-version">Type <strong>{E(prior.SourceVersion)}</strong> to confirm deletion</label>
                    <div class="delete-release-controls"><input id="confirm-delete-version" name="confirmVersion" autocomplete="off" required aria-label="Release version to delete">
                      <button class="button danger" type="submit">Delete {E(ReleaseName(prior.SourceVersion))} data</button></div>
                  </form>
                  """;

        var completedJobIsLive = job?.Status == "COMPLETED" && active?.SourceVersion == job.SourceVersion;
        var completedJobIsReady = job?.Status == "COMPLETED" && candidate?.SourceVersion == job.SourceVersion;
        var jobHtml = job is null ? "<p class='muted'>No update preparation has been started from this portal.</p>" :
            $"""
            <div class="job-summary"><div><strong>{E(ReleaseName(job.SourceVersion))}</strong><span class="badge {JobClass(job.Status)}">{E(completedJobIsLive ? "Live" : completedJobIsReady ? "Ready for review" : job.Status == "COMPLETED" ? "Previously prepared" : Status(job.Stage))}</span></div>
              <span class="muted">Started {Time(job.StartedAt ?? job.CreatedAt)}</span></div>
            {(job.Status == "FAILED" ? $"<p class='job-error'>{E(job.ErrorMessage)}</p><p class='muted'>{(active is not null && string.CompareOrdinal(job.SourceVersion, active.SourceVersion) < 0 && job.ErrorMessage?.Contains(" count dropped more than ", StringComparison.Ordinal) == true
                ? "This older release can be rechecked from its imported data. Choose it above and prepare again; the live API was not switched."
                : "Review the error, then choose the release above to retry. The live API was not switched.")}</p>" :
                completedJobIsLive ? "<p class='muted'>This release is live.</p>" :
                completedJobIsReady ? "<p class='muted'>Preparation is complete. Review the release below before activating it.</p>" :
                job.Status == "COMPLETED" ? "<p class='muted'>Preparation completed previously. This release is not currently live.</p>" :
                "<p class='muted'>The current release remains live while the new data is prepared. This page updates automatically.</p>")}
            <div id="job-progress" class="job-progress" {(job.Status is "QUEUED" or "RUNNING" ? "" : "hidden")}>
              <div class="progress-track"><div id="progress-fill" class="progress-fill"></div></div>
              <span id="progress-label">{E(Status(job.Stage))}</span>
            </div>
            """;

        string Row(DatasetDetail v) => $"""
            <tr><td><strong>{E(ReleaseName(v.SourceVersion))}</strong><small>{E(v.SourceVersion)}</small></td>
              <td><span class="badge {StatusClass(v.Status)}">{E(Status(v.Status))}</span></td>
              <td>{Count(v.AddressCount)}</td><td>{(v.GeocodeCoverage is null ? "—" : v.GeocodeCoverage.Value.ToString("P2", CultureInfo.InvariantCulture))}</td>
              <td>{Size(v.TableBytes)}</td><td>{Size(v.ArchiveBytes)}</td><td>{Time(v.ValidatedAt)}</td></tr>
            """;
        var history = !dataAvailable ? "<tr><td colspan='7'>Release details temporarily unavailable.</td></tr>" :
            national.Length == 0 ? "<tr><td colspan='7'>No national releases installed.</td></tr>" :
            string.Join("", national.Select(Row));
        var otherRows = string.Join("", other.Select(v => $"<tr><td>{E(v.SourceVersion)}</td><td>{E(v.DatasetName)}</td><td>{E(v.Scope)}</td><td>{E(v.Status)}</td></tr>"));
        var otherHtml = other.Length == 0 ? "" : $"""
            <details class="other-data"><summary>Other local datasets ({other.Length})</summary>
              <p class="muted">Regional and sample datasets are kept separate from national update controls.</p>
              <table><thead><tr><th>Version</th><th>Dataset</th><th>Scope</th><th>Status</th></tr></thead><tbody>{otherRows}</tbody></table>
            </details>
            """;

        static string Role(string role) => role switch
        {
            "primary" => "Serving addresses",
            "standby" => "Ready to take over",
            _ => "Not responding"
        };
        var nodeCards = string.Join("", cluster.Databases.Select(node => $"""
            <div class="cluster-node" data-host="{E(node.Host)}" data-role="{E(node.Role)}">
              <span class="cluster-node-name">{E(node.Name)}</span>
              <strong class="cluster-node-role">{E(Role(node.Role))}</strong>
              <span class="cluster-node-detail">{E(node.Host)} · {(node.Online ? "Online" : "Offline")}</span>
            </div>
            """));
        var primaryNode = cluster.Databases.FirstOrDefault(node => node.Role == "primary");
        var lagText = primaryNode?.ReplayLagBytes is long lag
            ? lag == 0 ? "Caught up" : $"{lag / 1024d:N0} KiB behind"
            : "Not available";
        var readyReplicas = apiReplicas.Count(node => node.Ready);
        var replicaState = readyReplicas == apiReplicas.Count && readyReplicas > 1 ? "healthy" :
            readyReplicas > 0 ? "degraded" : "unavailable";
        var replicaHeadline = replicaState switch
        {
            "healthy" => "Both API servers ready",
            "degraded" => "One API server ready",
            _ => "API servers unavailable"
        };
        var replicaCards = string.Join("", apiReplicas.Select(node => $"""
            <div class="cluster-node" data-api-host="{E(node.Host)}" data-role="{(node.Ready ? "ready" : "offline")}">
              <span class="cluster-node-name">{E(node.Name)}</span>
              <strong class="cluster-node-role">{(node.Ready ? "Ready for requests" : "Not responding")}</strong>
              <span class="cluster-node-detail">{E(node.Host)} · {(node.Ready ? "Online" : "Offline")}</span>
            </div>
            """));
        var retentionControl = !dataAvailable || retentionHours is null
            ? "<p class='muted'>Bulk retention settings will return when the database is available.</p>"
            : $"""
              <p class="cluster-detail">Uploads, results and job history are removed after <strong>{retentionHours} hours</strong> once a job finishes. Abandoned jobs are also cleared.</p>
              <form class="retention-form" method="post" action="/settings/bulk-retention">
                {csrfField}
                <label for="retention-hours">Keep completed bulk data for</label>
                <select id="retention-hours" name="retentionHours">
                  {string.Join("", new[] { 1, 6, 12, 24, 48, 72, 168 }.Select(hours =>
                      $"<option value='{hours}'{(hours == retentionHours ? " selected" : "")}>{(hours == 1 ? "1 hour" : hours < 24 ? $"{hours} hours" : hours == 24 ? "24 hours" : $"{hours / 24} days")}</option>"))}
                </select>
                <button class="button primary" type="submit">Save retention</button>
              </form>
              <p class="muted">Changes apply immediately. Older finished jobs may be deleted at the next cleanup check.</p>
              """;
        var housekeepingState = housekeeping?.State ?? "pending";
        var housekeepingHeadline = housekeepingState switch
        {
            "healthy" => "Storage check passed",
            "attention" => "Storage needs attention",
            _ => "Checking storage"
        };

        return $"""
            <!doctype html>
            <html lang="en-AU"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
              <title>AddressDesk · G-NAF Control Centre</title><link rel="stylesheet" href="/admin.css" defer>
              <script src="/admin.js" defer></script></head>
            <body data-job-active="{(job?.Status is "QUEUED" or "RUNNING" ? "true" : "false")}">
              <div class="shell"><header class="topbar"><a class="brand" href="/" aria-label="AddressDesk operations home">Address<span>Desk</span></a>
                <span class="portal-name">Operations</span>
                <a class="api-link" href="http://127.0.0.1:8080/" target="_blank" rel="noopener">Address validation ↗</a></header>
              <main>
                <div class="admin-hero-grid">
                  <div class="page-title"><div><span class="eyebrow">BUILT FOR AUSTRALIAN ADDRESS DATA</span><h1>Keep national address data ready.</h1>
                      <p>Prepare, review and activate G-NAF releases while the address service stays online.</p></div>
                      <span class="environment">{E(operatorName)}</span></div>
                  <section class="hero" aria-label="Current service status">
                    <div class="hero-main"><span class="eyebrow">CURRENT NATIONAL RELEASE</span><h2>{E(activeName)}</h2>
                      <p>{E(activeVersion)} <span class="hero-separator">·</span> {Count(active?.AddressCount)} addresses</p>
                      <div class="hero-facts"><div><span>API servers</span><strong>{readyReplicas}/{apiReplicas.Count} ready</strong></div>
                        <div><span>Databases</span><strong>{cluster.Databases.Count(node => node.Online)}/{cluster.Databases.Count} online</strong></div></div></div>
                    <div class="hero-health"><span id="api-status-dot" class="health-dot {apiClass}"></span><strong id="api-status-text">{E(apiText)}</strong>
                      <span id="api-status-detail">{(apiReady ? "Address lookups are available" : "Check the API container and database")}</span></div>
                  </section>
                </div>
                {noticeBox}{errorBox}
                <div class="workflow-heading"><div><span class="eyebrow">RELEASE MANAGEMENT</span><h2>Choose and prepare a release</h2></div>
                  <p>Choose any official national release. Review its checks before switching the live service.</p></div>
                <div class="grid">
                  <section class="panel step"><div class="step-heading"><span class="step-number">01</span><div><h3>Choose an official release</h3><p>Current and archived national GDA2020 releases are listed by date.</p></div></div>
                    <div class="release-actions"><button class="button secondary" id="check-releases" type="button">Refresh official releases</button>
                      <button class="button secondary compact" id="check-latest" type="button" disabled>Check latest</button></div>
                    <label class="release-label" for="release-select">Release to prepare</label>
                    <select id="release-select" class="release-select" disabled><option value="">Loading official releases…</option></select>
                    <div id="latest-result" class="latest-result" role="status" aria-live="polite"></div>
                    <form id="prepare-form" method="post" action="/prepare" hidden>{csrfField}<input type="hidden" name="version" id="prepare-version"><button class="button primary" type="submit">Prepare selected release</button></form>
                  </section>
                  <section class="panel step"><div class="step-heading"><span class="step-number">02</span><div><h3>Prepare in the background</h3><p>Download, import, index and verify. The live release stays in service.</p></div></div>
                    {jobHtml}</section>
                  <section class="panel step wide{(candidate is null ? " empty" : "")}"><div class="step-heading"><span class="step-number">03</span><div><h3>Review and activate</h3><p>A release appears here only after its quality checks pass.</p></div></div>
                    {comparison}</section>
                </div>
                <section class="panel rollback-panel"><div><span class="eyebrow">RECOVERY</span><h3>Return to the previous release</h3>
                    {rollback}</div><span class="recovery-icon" aria-hidden="true">↶</span></section>
                <section class="panel delete-panel" aria-label="Manage retained release"><span class="eyebrow">STORAGE</span><h3>Delete previous release data</h3>
                  {deleteRetired}</section>
                <section class="history"><div class="section-heading"><div><span class="eyebrow">RELEASE HISTORY</span><h2>Installed national releases</h2></div><span>Database size: {Size(databaseBytes)} per node · 2 copies</span></div>
                  <div class="table-wrap"><table><thead><tr><th>Release</th><th>State</th><th>Addresses</th><th>Geocoded</th><th>Serving data + indexes</th><th>Original ZIP size</th><th>Checked</th></tr></thead>
                    <tbody>{history}</tbody></table></div>{otherHtml}</section>
                <div class="workflow-heading operations-heading"><div><span class="eyebrow">OPERATIONS</span><h2>Service and storage settings</h2></div></div>
                <section class="cluster-panel" aria-label="Database and failover status" data-cluster-state="{E(cluster.State)}">
                  <div class="cluster-heading"><div><span class="eyebrow">DATABASE PROTECTION</span><h2>Database and failover status</h2></div>
                    <span id="cluster-badge" class="cluster-badge {E(cluster.State)}">{E(cluster.Headline)}</span></div>
                  <p id="cluster-detail" class="cluster-detail">{E(cluster.Detail)}</p>
                  <div id="cluster-nodes" class="cluster-nodes">{nodeCards}</div>
                  <div class="cluster-facts"><span id="cluster-coordinators">Coordinators: {cluster.CoordinatorsOnline}/{cluster.CoordinatorsTotal} online</span>
                    <span id="cluster-lag">Replica: {E(lagText)}</span><span>Both databases run on this computer.</span></div>
                </section>
                <section class="cluster-panel" aria-label="API server status" data-api-state="{replicaState}">
                  <div class="cluster-heading"><div><span class="eyebrow">API PROTECTION</span><h2>Address service servers</h2></div>
                    <span id="api-replicas-badge" class="cluster-badge {replicaState}">{replicaHeadline}</span></div>
                  <p id="api-replicas-detail" class="cluster-detail">{readyReplicas} of {apiReplicas.Count} API servers ready. The gateway directs requests to ready servers.</p>
                  <div id="api-replica-nodes" class="cluster-nodes">{replicaCards}</div>
                </section>
                <section class="cluster-panel" aria-label="Bulk data retention">
                  <div class="cluster-heading"><div><span class="eyebrow">BULK JOBS</span><h2>Data retention</h2></div></div>
                  {retentionControl}
                </section>
                <section class="cluster-panel" aria-label="Automatic maintenance status">
                  <div class="cluster-heading"><div><span class="eyebrow">AUTOMATIC MAINTENANCE</span><h2>Storage housekeeping</h2></div>
                    <span class="cluster-badge {(housekeepingState == "healthy" ? "healthy" : "degraded")}">{E(housekeepingHeadline)}</span></div>
                  <p class="cluster-detail">{E(housekeeping?.Detail ?? "The first storage check has not finished yet.")}</p>
                  <div class="cluster-facts"><span>Last checked: {Time(housekeeping?.CheckedAtUtc)}</span>
                    <span>Free space: {Size(housekeeping?.AvailableBytes)}</span>
                    <span>G-NAF cache: {Size(housekeeping?.CacheBytes)}</span>
                    <span>Files removed in last sweep: {housekeeping?.RemovedFiles ?? 0}</span></div>
                  <p class="muted">PostgreSQL handles routine vacuuming and query statistics. This local stack has no scheduled off-computer backup.</p>
                </section>
                <section class="history" aria-label="Operator activity"><div class="section-heading"><div><span class="eyebrow">AUDIT HISTORY</span><h2>Recent operator actions</h2></div><span>Most recent 20 actions · UTC</span></div>
                  <div class="activity-panel">{activity}</div></section>
              </main>
              <footer><span>G-NAF © Geoscape Australia, licensed by the Commonwealth of Australia.</span>
                <span>G-NAF matching does not verify postal delivery. <a href="https://data.gov.au/data/dataset/19432f89-dc3a-4ef3-b943-5326ef1dbecc" target="_blank" rel="noopener">Official source ↗</a></span></footer></div>
            </body></html>
            """;
    }

    private static string StatusClass(string status) => status switch
    {
        "ACTIVE" => "success",
        "READY" => "ready",
        "RETIRED" => "neutral",
        "FAILED" => "danger",
        _ => "working"
    };

    private static string JobClass(string status) => status switch
    {
        "COMPLETED" => "success",
        "FAILED" => "danger",
        _ => "working"
    };

    private static string EventClass(string outcome) => outcome switch
    {
        "SUCCEEDED" => "success",
        "REJECTED" => "neutral",
        _ => "danger"
    };
}
